package main

import "fmt"

// 题目：打印一个整数在机器中的二进制表示。
// 整数的每一位都可以通过右移或掩码判断是否为 1。
// 通常从最高位到最低位依次检查，这样打印结果符合人阅读二进制的顺序。
// 核心思路：用 1 左移到指定位，与原数做按位与，结果非 0 表示该位为 1。
// 时间复杂度：O(1)，固定检查整数位数。
// 空间复杂度：O(1)。

func main() {
	printBinary(11)
}

// printBinary 打印一个数的二进制
// num & (1 << i) 能判断 num 的第 i 位是 0 还是 1，核心是利用按位与（&:都为1，结果为1；否则是0）运算的特性 + 掩码（1 << i）的构造逻辑
func printBinary(n int) {
	for i := 31; i >= 0; i-- {
		if n&(1<<i) == 0 {
			fmt.Print(0)
		} else {
			fmt.Print(1)
		}

	}
}
